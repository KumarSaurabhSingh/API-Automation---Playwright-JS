const { randomString, randomInt, randomFloat } = require('../utils/data-generator');

class ProductBuilder {
  constructor() {
    this.reset();
  }

  reset() {
    this.payload = {
      title: `Automated Product ${randomString(6)}`,
      description: `Product generated by the API automation framework at ${new Date().toISOString()}`,
      price: randomFloat(5, 499.99),
      discountPercentage: randomFloat(0, 25),
      rating: randomFloat(1, 5),
      stock: randomInt(1, 250),
      brand: `Brand ${randomString(4).toUpperCase()}`,
      category: 'beauty',
      thumbnail: 'https://cdn.dummyjson.com/product-images/beauty/essence-mascara-lash-princess/thumbnail.webp',
    };
    return this;
  }

  with(overrides) {
    this.payload = { ...this.payload, ...overrides };
    return this;
  }

  withTitle(title) {
    this.payload.title = title;
    return this;
  }

  withPrice(price) {
    this.payload.price = price;
    return this;
  }

  withStock(stock) {
    this.payload.stock = stock;
    return this;
  }

  withCategory(category) {
    this.payload.category = category;
    return this;
  }

  withBrand(brand) {
    this.payload.brand = brand;
    return this;
  }

  build() {
    return { ...this.payload };
  }
}

module.exports = ProductBuilder;
